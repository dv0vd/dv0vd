#!/bin/bash
set -e # stop script on any error

# Завершает все процессы, которые держат tcp/udp-порт из переданного диапазона MIN-MAX.
# Использование: free_ports.sh MIN-MAX [MIN-MAX ...]  (одиночный порт передаётся как X-X)
#
# Принцип работы:
# 1. ss -H -l -n -p -t|-u — один прогон по таблице сокетов:
#    -H без заголовка, -n без резолва имён, -p со списком процессов;
#    -l только привязанные сокеты (для tcp это LISTEN, для udp — UNCONN), поэтому исходящие
#    соединения, чей локальный ephemeral-порт случайно попал в диапазон, не задеваются;
#    при одном протоколе колонки такие: State Recv-Q Send-Q Local Peer [Process],
#    то есть локальный адрес всегда 4-е поле, а колонка процессов добавляется в конец.
# 2. awk оставляет только строки, где порт из 4-го поля попадает в [from, to]:
#    sub(/.*:/, "", local) берёт часть после последнего двоеточия (0.0.0.0:53, [::]:53, *:53),
#    "+0" приводит строку к числу, чтобы сравнение с границами диапазона было числовым.
# 3. grep -o 'pid=[0-9]*' + cut -d= -f2 достают pid'ы из поля users:((...)): на одном сокете
#    их может быть несколько (fork, SO_REUSEPORT), sort -u убирает дубли.
# 4. kill -KILL по собранному списку: ядро освобождает порты сразу, поэтому graceful-схема
#    (TERM + ожидание) здесь не нужна — она только оттягивала бы старт контейнера.

holder_pids() {
  ss -H -l -n -p "$1" | awk -v from="${from}" -v to="${to}" '
    {
      local = $4
      sub(/.*:/, "", local)
      if (local + 0 < from || local + 0 > to) next
      print $0
    }' | grep -o 'pid=[0-9]*' | cut -d'=' -f2 | sort -u
}

for range in "$@"; do
  from="${range%%-*}"
  to="${range##*-}"

  pids="$(holder_pids -t; holder_pids -u)"

  kill -KILL ${pids} 2>/dev/null || true
done
